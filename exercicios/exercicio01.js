// o que é:

// 1. Erro
// 2. Exceção
// 3. Diferença entre “erro” em linguagem natural e “exceção” em JavaScript

function definicoesBasicas() {
    console.log("1. Erro: é um problema no código que faz o programa não funcionar como esperado.");

    console.log("2. Exceção: é uma ocorrência durante a execução do programa que pode interromper o fluxo normal e ser tratada.");

    console.log("3. Diferença: na linguagem natural, erro significa algo que deu errado. Em JavaScript, exceção é uma ocorrência durante a execução que pode ser lançada e tratada pelo programa.");
}

definicoesBasicas();